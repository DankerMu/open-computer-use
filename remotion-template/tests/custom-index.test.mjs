// The generated src/custom/index.ts: its exact text with and without a
// custom scene, the tracked copy in the template, and writeCustomIndex's
// refusals. Expected texts come from the task 3.8 fixture.

import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { customIndexSource, writeCustomIndex } from "../bin/custom-index.mjs";
import { Refusal } from "../bin/kit-io.mjs";
import { validateScript } from "../bin/script-schema.mjs";
import { fixtureScript } from "./render/fixtures/explainer/fixture.mjs";

const HEADER = "// Generated by node bin/kit.mjs from script.json. Do not edit: kit check and kit render rewrite it.\n";
const ORBIT_INDEX = `${HEADER}export { default } from './Orbit.tsx';\nexport const component = 'Orbit';\n`;
const NULL_INDEX = `${HEADER}export default null;\nexport const component = null;\n`;
const CUSTOM = "chapter 2 原理, scene 1 (custom)";
const PREVIOUS = "// the index before the refused run\n";

function templateScript() {
  const result = validateScript(readFileSync(new URL("../script.json", import.meta.url), "utf8"));
  assert.equal(result.ok, true);
  return result.script;
}

// A project root with src/custom/ holding Orbit.tsx and a previous index,
// plus a regular file and a directory outside it for links to point at.
function project(t) {
  const root = mkdtempSync(join(tmpdir(), "custom-index-test-"));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  const dir = join(root, "src", "custom");
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, "Orbit.tsx"), "export default function Orbit() {\n\treturn null;\n}\n");
  writeFileSync(join(dir, "index.ts"), PREVIOUS);
  mkdirSync(join(root, "elsewhere"));
  writeFileSync(join(root, "elsewhere", "Orbit.tsx"), "export default function Orbit() {\n\treturn null;\n}\n");
  return { root, dir };
}

function listing(dir) {
  return readdirSync(dir).sort();
}

async function refuses(promise, message) {
  await assert.rejects(promise, (error) => error instanceof Refusal && error.message === message);
}

test("the source names the custom scene's file and component", () => {
  assert.equal(customIndexSource(fixtureScript()), ORBIT_INDEX);
});

test("without a custom scene the source exports null", () => {
  assert.equal(customIndexSource(templateScript()), NULL_INDEX);
});

test("the tracked src/custom/index.ts is the source for the template's script.json", () => {
  const tracked = readFileSync(new URL("../src/custom/index.ts", import.meta.url), "utf8");
  assert.equal(tracked, customIndexSource(templateScript()));
  assert.equal(tracked, NULL_INDEX);
});

test("writeCustomIndex writes the source, the same bytes when run twice, and no partial file", async (t) => {
  const { root, dir } = project(t);
  await writeCustomIndex(root, fixtureScript());
  assert.equal(readFileSync(join(dir, "index.ts"), "utf8"), ORBIT_INDEX);
  await writeCustomIndex(root, fixtureScript());
  assert.equal(readFileSync(join(dir, "index.ts"), "utf8"), ORBIT_INDEX);
  assert.deepEqual(listing(dir), ["Orbit.tsx", "index.ts"]);
  await writeCustomIndex(root, templateScript());
  assert.equal(readFileSync(join(dir, "index.ts"), "utf8"), NULL_INDEX);
});

// [name, change to the project, script, expected message given the root].
const REFUSALS = [
  ["a missing custom file", ({ dir }) => rmSync(join(dir, "Orbit.tsx")), fixtureScript, () => `${CUSTOM}: src/custom/Orbit.tsx is missing`],
  [
    "a symlinked custom file",
    ({ root, dir }) => {
      rmSync(join(dir, "Orbit.tsx"));
      symlinkSync(join(root, "elsewhere", "Orbit.tsx"), join(dir, "Orbit.tsx"));
    },
    fixtureScript,
    () => `${CUSTOM}: src/custom/Orbit.tsx is a symlink`,
  ],
  [
    "a directory in the custom file's place",
    ({ dir }) => {
      rmSync(join(dir, "Orbit.tsx"));
      mkdirSync(join(dir, "Orbit.tsx"));
    },
    fixtureScript,
    () => `${CUSTOM}: src/custom/Orbit.tsx is not a regular file`,
  ],
];

for (const [name, change, script, message] of REFUSALS) {
  test(`writeCustomIndex refuses ${name} and writes nothing`, async (t) => {
    const p = project(t);
    change(p);
    const before = listing(p.dir);
    await refuses(writeCustomIndex(p.root, script()), message(p));
    assert.deepEqual(listing(p.dir), before);
    assert.equal(readFileSync(join(p.dir, "index.ts"), "utf8"), PREVIOUS);
  });
}

// [name, change to src/custom, script, problem].
const DIR_REFUSALS = [
  ["a missing src/custom/", ({ dir }) => rmSync(dir, { recursive: true }), fixtureScript, "is missing"],
  ["a missing src/custom/ for a script without a custom scene", ({ dir }) => rmSync(dir, { recursive: true }), templateScript, "is missing"],
  [
    "a symlinked src/custom/",
    ({ root, dir }) => {
      rmSync(dir, { recursive: true });
      symlinkSync(join(root, "elsewhere"), dir);
    },
    fixtureScript,
    "is a symlink",
  ],
  [
    "a symlinked src/custom/ for a script without a custom scene",
    ({ root, dir }) => {
      rmSync(dir, { recursive: true });
      symlinkSync(join(root, "elsewhere"), dir);
    },
    templateScript,
    "is a symlink",
  ],
  [
    "a file in src/custom/'s place",
    ({ dir }) => {
      rmSync(dir, { recursive: true });
      writeFileSync(dir, PREVIOUS);
    },
    fixtureScript,
    "is not a directory",
  ],
];

for (const [name, change, script, problem] of DIR_REFUSALS) {
  test(`writeCustomIndex refuses ${name} and writes nothing`, async (t) => {
    const p = project(t);
    change(p);
    const src = join(p.root, "src");
    const before = listing(src);
    const elsewhere = listing(join(p.root, "elsewhere"));
    await refuses(writeCustomIndex(p.root, script()), `${p.root}/src/custom: ${problem}`);
    assert.deepEqual(listing(src), before);
    assert.deepEqual(listing(join(p.root, "elsewhere")), elsewhere);
  });
}
