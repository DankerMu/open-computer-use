// The generated src/custom/index.ts: one static re-export of the custom
// scene's file, so the Remotion bundle can resolve it, and the component's
// name, which the renderer compares with script.json. Both functions take a
// script returned by validateScript: its component pattern,
// ^[A-Z][A-Za-z0-9]{0,39}$, keeps the name inside src/custom/ and inside
// the generated import string. CLI-side; the bundle never imports this.

import { join } from "node:path";
import { Refusal, lstatOrNull, writeAtomic } from "./kit-io.mjs";
import { playbackWhere } from "./script-schema.mjs";

const HEADER = "// Generated by node bin/kit.mjs from script.json. Do not edit: kit check and kit render rewrite it.\n";
const INDEX = "index.ts";

// The custom scene with its where, or null.
function customScene(script) {
  const scenes = script.chapters.flatMap((chapter) => chapter.scenes);
  const index = scenes.findIndex((scene) => scene.kind === "custom");
  if (index === -1) return null;
  // Playback index: the hook is 1, so the chapter scenes start at 2.
  return { component: scenes[index].component, where: playbackWhere(script, index + 2) };
}

export function customIndexSource(script) {
  const custom = customScene(script);
  if (custom === null) return `${HEADER}export default null;\nexport const component = null;\n`;
  return `${HEADER}export { default } from './${custom.component}.tsx';\nexport const component = '${custom.component}';\n`;
}

// Checks root/src/custom/ and the custom scene's file with lstat, then
// replaces root/src/custom/index.ts atomically. Writes nothing on a refusal.
export async function writeCustomIndex(root, script) {
  const dir = join(root, "src", "custom");
  const dirStat = await lstatOrNull(dir);
  if (dirStat === null) throw new Refusal(`${dir}: is missing`);
  if (dirStat.isSymbolicLink()) throw new Refusal(`${dir}: is a symlink`);
  if (!dirStat.isDirectory()) throw new Refusal(`${dir}: is not a directory`);
  const custom = customScene(script);
  if (custom !== null) {
    const name = `src/custom/${custom.component}.tsx`;
    const stat = await lstatOrNull(join(dir, `${custom.component}.tsx`));
    if (stat === null) throw new Refusal(`${custom.where}: ${name} is missing`);
    if (stat.isSymbolicLink()) throw new Refusal(`${custom.where}: ${name} is a symlink`);
    if (!stat.isFile()) throw new Refusal(`${custom.where}: ${name} is not a regular file`);
  }
  await writeAtomic(dir, INDEX, customIndexSource(script));
}
